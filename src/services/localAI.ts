export const downloadModel = async (
  modelName: string, 
  progressCallback?: (progress: number) => void
): Promise<boolean> => {
  
  for (let i = 0; i <= 100; i += 10) {
    if (progressCallback) {
      progressCallback(i);
    }
    await new Promise(resolve => setTimeout(resolve, 500));
  }
  
  return true;
};
